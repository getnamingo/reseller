use Namingo\ResellerApi\Ownership;
use Namingo\ResellerApi\Util;

$command = $argv[1] ?? 'help';
if ($command === 'key:generate') {
    echo 'base64:' . base64_encode(random_bytes(32)) . PHP_EOL;
    exit(0);
}

$root = dirname(__DIR__);
require $root . '/vendor/autoload.php';

Config::load($root);

