    echo PHP_EOL;
};

$arg = static function (int $index, string $name) use ($argv): string {
    $value = $argv[$index] ?? '';
    if ($value === '') {
        throw new RuntimeException("Missing argument: {$name}");
    }
    return $value;
};

$uuid = static function (string $value, string $name): string {
    if (!Util::isUuid($value)) {
        throw new RuntimeException("{$name} must be a UUID generated by this application.");
    }
    return strtolower($value);
};

$priceScope = static function (string $zone, string $years): array {
    $tld = $zone === '-' ? '' : strtolower(ltrim($zone, '.'));
    if ($tld !== '') {
        Ownership::name('example.' . $tld, 'domain');
    }
    if (strlen($tld) > 253 || preg_match('/^(?:[0-9]|10)$/D', $years) !== 1) {
        throw new RuntimeException('Invalid TLD or period (0-10 years).');
    }
    return [$tld, (int) $years];
};

$secret = static function (string $prompt): string {
    fwrite(STDERR, $prompt);
    $hidden = function_exists('stream_isatty') && stream_isatty(STDIN) && PHP_OS_FAMILY !== 'Windows';
    if ($hidden) {
        exec('stty -echo');
    }
    try {
        $value = fgets(STDIN);
    } finally {
        if ($hidden) {
            exec('stty echo');
            fwrite(STDERR, PHP_EOL);
        }
    }
    if ($value === false) {
        throw new RuntimeException('Could not read password.');
    }
    return rtrim($value, "\r\n");
};

$newPassword = static function () use ($secret): string {
    $first = $secret('Password (minimum 14 characters): ');
    $second = $secret('Confirm password: ');
    if (!hash_equals($first, $second)) {
        throw new RuntimeException('Passwords do not match.');
    }
    if (strlen($first) < 14 || strlen($first) > 1024) {
        throw new RuntimeException('Password must contain 14-1024 bytes.');
    }
    return $first;
};

$readConfig = static function (string $source): array {
    $raw = $source === '-' ? stream_get_contents(STDIN) : file_get_contents($source);
    if ($raw === false || $raw === '') {
        throw new RuntimeException('Registry configuration could not be read.');
    }
    $config = json_decode($raw, true, 32, JSON_THROW_ON_ERROR);
    if (!is_array($config) || ($config !== [] && array_is_list($config))) {
        throw new RuntimeException('Registry configuration must be a JSON object.');
    }
    return $config;
};

try {
    if (in_array($command, ['help', '--help', '-h'], true)) {
        $help();
        exit(0);
    }

    $pdo = Db::pdo();

    switch ($command) {
        case 'migrate':
            $exists = $pdo->query("SHOW TABLES LIKE 'schema_migrations'")->fetchColumn();
            if ($exists !== false && !$pdo->query("SELECT 1 FROM schema_migrations WHERE version = '002_ownership_pricing'")->fetchColumn()) {
                if ($pdo->query("SELECT 1 FROM epp_jobs WHERE status IN ('queued', 'processing', 'unknown') LIMIT 1")->fetchColumn()) {
                    throw new RuntimeException('Reconcile all unfinished jobs before this migration.');
                }
                $pdo->exec(file_get_contents($root . '/database/002_ownership_pricing.sql'));
            }
            if ($exists !== false && !$pdo->query("SELECT 1 FROM schema_migrations WHERE version = '003_foundry_panel'")->fetchColumn()) {
                $pdo->exec(file_get_contents($root . '/database/003_foundry_panel.sql'));
            }
            if ($exists !== false && !$pdo->query("SELECT 1 FROM schema_migrations WHERE version = '004_lifecycle_queue'")->fetchColumn()) {
                $pdo->exec(file_get_contents($root . '/database/004_lifecycle_queue.sql'));
            }
            $sql = file_get_contents($root . '/database/schema.sql');
            if ($sql === false) {
                throw new RuntimeException('database/schema.sql is missing.');
            }
            $pdo->exec($sql);
            echo "Database schema is ready.\n";
            break;

        case 'user:create':
            $username = $arg(2, 'USERNAME');
            $currency = strtoupper($arg(3, 'CURRENCY'));
            if (preg_match('/^[A-Za-z0-9][A-Za-z0-9._-]{2,63}$/D', $username) !== 1) {
                throw new RuntimeException('Username must contain 3-64 safe ASCII characters.');
            }
            if (preg_match('/^[A-Z]{3}$/D', $currency) !== 1) {
                throw new RuntimeException('Currency must be a three-letter ISO code.');
            }
            $password = $newPassword();
            $resellerId = Util::uuid();
            $pdo->beginTransaction();
            try {
                $insert = $pdo->prepare(
                    'INSERT INTO resellers (id, username, password_hash, currency) VALUES (?, ?, ?, ?)'
                );
                $insert->execute([$resellerId, $username, password_hash($password, PASSWORD_ARGON2ID), $currency]);
                $wallet = $pdo->prepare('INSERT INTO wallets (reseller_id, currency) VALUES (?, ?)');
                $wallet->execute([$resellerId, $currency]);
                $pdo->commit();
            } catch (Throwable $e) {
                if ($pdo->inTransaction()) {
                    $pdo->rollBack();
                }
                throw $e;
            }
            sodium_memzero($password);
            Audit::record($pdo, $resellerId, 'admin.user_created', 'reseller', $resellerId);
            echo $resellerId . PHP_EOL;
            break;

        case 'user:role':
            $resellerId = $uuid($arg(2, 'RESELLER_UUID'), 'RESELLER_UUID');
            $role = $arg(3, '0|1');
            if (!in_array($role, ['0', '1'], true)) {
                throw new RuntimeException('Role must be 0 (administrator) or 1 (reseller).');
            }
            $pdo->prepare('UPDATE resellers SET role = ? WHERE id = ?')->execute([$role, $resellerId]);
            Audit::record($pdo, $resellerId, 'admin.role_changed', 'reseller', $resellerId, null, ['role' => $role]);
            echo "Role updated.\n";
            break;

        case 'tld:add':
        case 'tld:status':
            $registryId = $uuid($arg(2, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $tld = Access::tld($arg(3, 'TLD'));
            $state = $command === 'tld:add' ? 'enabled' : $arg(4, 'enabled|disabled');
            if (!in_array($state, ['enabled', 'disabled'], true)) {
                throw new RuntimeException('State must be enabled or disabled.');
            }
            $pdo->prepare('INSERT INTO registry_tlds (registry_id, tld, enabled) VALUES (?, ?, ?) ON DUPLICATE KEY UPDATE enabled = VALUES(enabled)')
                ->execute([$registryId, $tld, (int) ($state === 'enabled')]);
            Audit::record($pdo, null, 'admin.tld_saved', 'registry', $registryId, null, ['tld' => $tld, 'state' => $state]);
            echo "TLD saved.\n";
            break;

        case 'tld:grant':
        case 'tld:revoke':
            $resellerId = $uuid($arg(2, 'RESELLER_UUID'), 'RESELLER_UUID');
            $registryId = $uuid($arg(3, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $tld = Access::tld($arg(4, 'TLD'));
            $pdo->prepare('INSERT INTO reseller_tlds (reseller_id, registry_id, tld, enabled) VALUES (?, ?, ?, ?) ON DUPLICATE KEY UPDATE enabled = VALUES(enabled)')
                ->execute([$resellerId, $registryId, $tld, (int) ($command === 'tld:grant')]);
            Audit::record($pdo, $resellerId, 'admin.' . str_replace(':', '_', $command), 'registry', $registryId, null, ['tld' => $tld]);
            echo "TLD permission saved.\n";
            break;

        case 'auth:prune':
            $pdo->exec('DELETE FROM auth_login_limits WHERE window_started < UTC_TIMESTAMP(6) - INTERVAL 1 DAY');
            $pdo->exec('DELETE FROM auth_tokens WHERE expires_at < UTC_TIMESTAMP(6) - INTERVAL 1 DAY');
            echo "Expired login limits and tokens pruned.\n";
            break;

        case 'user:password':
            $resellerId = $uuid($arg(2, 'RESELLER_UUID'), 'RESELLER_UUID');
            $password = $newPassword();
            $stmt = $pdo->prepare('UPDATE resellers SET password_hash = ?, failed_logins = 0, locked_until = NULL WHERE id = ?');
            $stmt->execute([password_hash($password, PASSWORD_ARGON2ID), $resellerId]);
            sodium_memzero($password);
            if ($stmt->rowCount() !== 1) {
                throw new RuntimeException('Reseller not found.');
            }
            $revoke = $pdo->prepare('UPDATE auth_tokens SET revoked_at = UTC_TIMESTAMP(6) WHERE reseller_id = ? AND revoked_at IS NULL');
            $revoke->execute([$resellerId]);
            Audit::record($pdo, $resellerId, 'admin.password_changed', 'reseller', $resellerId);
            echo "Password changed and existing tokens revoked.\n";
            break;

        case 'user:status':
            $resellerId = $uuid($arg(2, 'RESELLER_UUID'), 'RESELLER_UUID');
            $status = $arg(3, 'active|suspended');
            if (!in_array($status, ['active', 'suspended'], true)) {
                throw new RuntimeException('Status must be active or suspended.');
            }
            $stmt = $pdo->prepare('UPDATE resellers SET status = ? WHERE id = ?');
            $stmt->execute([$status, $resellerId]);
            if ($stmt->rowCount() !== 1) {
                throw new RuntimeException('Reseller not found or already in that state.');
            }
            if ($status === 'suspended') {
                $revoke = $pdo->prepare('UPDATE auth_tokens SET revoked_at = UTC_TIMESTAMP(6) WHERE reseller_id = ? AND revoked_at IS NULL');
                $revoke->execute([$resellerId]);
            }
            Audit::record($pdo, $resellerId, 'admin.user_' . $status, 'reseller', $resellerId);
            echo "Reseller status updated.\n";
            break;

        case 'token:revoke-all':
            $resellerId = $uuid($arg(2, 'RESELLER_UUID'), 'RESELLER_UUID');
            $stmt = $pdo->prepare('UPDATE auth_tokens SET revoked_at = UTC_TIMESTAMP(6) WHERE reseller_id = ? AND revoked_at IS NULL');
            $stmt->execute([$resellerId]);
            Audit::record($pdo, $resellerId, 'admin.tokens_revoked', 'reseller', $resellerId, null, ['count' => $stmt->rowCount()]);
            echo $stmt->rowCount() . " token(s) revoked.\n";
            break;

        case 'registry:add':
            $profile = CommandCatalog::normalizeProfile($arg(2, 'PROFILE'));
            $name = trim($arg(3, 'NAME'));
            if ($name === '' || !mb_check_encoding($name, 'UTF-8') || mb_strlen($name) > 128 || preg_match('/[\x00-\x1F\x7F]/u', $name) === 1) {
                throw new RuntimeException('Registry name must contain 1-128 printable characters.');
            }
            $config = EppWorker::validateRegistryConfig($profile, $readConfig($arg(4, 'CONFIG_JSON_FILE|-')));
            $registryId = Util::uuid();
            [$nonce, $cipher] = Crypto::encrypt(Util::json($config), 'registry-config:' . $registryId);
            $stmt = $pdo->prepare(
                'INSERT INTO registries (id, name, profile, config_nonce, config_cipher) VALUES (?, ?, ?, ?, ?)'
            );
            $stmt->execute([$registryId, $name, $profile, $nonce, $cipher]);
            Audit::record($pdo, null, 'admin.registry_added', 'registry', $registryId, null, ['profile' => $profile]);
            echo $registryId . PHP_EOL;
            break;

        case 'registry:update':
            $registryId = $uuid($arg(2, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $profile = CommandCatalog::normalizeProfile($arg(3, 'PROFILE'));
            $name = trim($arg(4, 'NAME'));
            if ($name === '' || !mb_check_encoding($name, 'UTF-8') || mb_strlen($name) > 128 || preg_match('/[\x00-\x1F\x7F]/u', $name) === 1) {
                throw new RuntimeException('Registry name must contain 1-128 printable characters.');
            }
            $config = EppWorker::validateRegistryConfig($profile, $readConfig($arg(5, 'CONFIG_JSON_FILE|-')));
            [$nonce, $cipher] = Crypto::encrypt(Util::json($config), 'registry-config:' . $registryId);
            $stmt = $pdo->prepare(
                'UPDATE registries SET name = ?, profile = ?, config_nonce = ?, config_cipher = ? WHERE id = ?'
            );
            $stmt->execute([$name, $profile, $nonce, $cipher, $registryId]);
            if ($stmt->rowCount() !== 1) {
                throw new RuntimeException('Registry not found or configuration unchanged.');
            }
            Audit::record($pdo, null, 'admin.registry_updated', 'registry', $registryId, null, ['profile' => $profile]);
            echo "Registry updated.\n";
            break;

        case 'registry:status':
            $registryId = $uuid($arg(2, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $status = $arg(3, 'enabled|disabled');
            if (!in_array($status, ['enabled', 'disabled'], true)) {
                throw new RuntimeException('Registry status must be enabled or disabled.');
            }
            $stmt = $pdo->prepare('UPDATE registries SET enabled = ? WHERE id = ?');
            $stmt->execute([$status === 'enabled' ? 1 : 0, $registryId]);
            if ($stmt->rowCount() !== 1) {
                throw new RuntimeException('Registry not found or already in that state.');
            }
            Audit::record($pdo, null, 'admin.registry_' . $status, 'registry', $registryId);
            echo "Registry status updated.\n";
            break;

        case 'registry:grant':
        case 'registry:revoke':
            $resellerId = $uuid($arg(2, 'RESELLER_UUID'), 'RESELLER_UUID');
            $registryId = $uuid($arg(3, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $enabled = $command === 'registry:grant' ? 1 : 0;
            $stmt = $pdo->prepare(
                'INSERT INTO reseller_registries (reseller_id, registry_id, enabled) VALUES (?, ?, ?)
                 ON DUPLICATE KEY UPDATE enabled = VALUES(enabled)'
            );
            $stmt->execute([$resellerId, $registryId, $enabled]);
            Audit::record($pdo, $resellerId, 'admin.' . str_replace(':', '_', $command), 'registry', $registryId);
            echo $enabled ? "Registry access granted.\n" : "Registry access revoked.\n";
            break;

        case 'price:set':
            $registryId = $uuid($arg(2, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $eppCommand = $arg(3, 'COMMAND');
            CommandCatalog::method($eppCommand);
            $rawAmount = $arg(4, 'AMOUNT');
            $amount = preg_match('/^0(?:\.0{1,4})?$/D', $rawAmount) === 1 ? '0.0000' : Util::money($rawAmount);
            $currency = strtoupper($arg(5, 'CURRENCY'));
            if (preg_match('/^[A-Z]{3}$/D', $currency) !== 1) {
                throw new RuntimeException('Currency must be a three-letter ISO code.');
            }
            $scope = $argv[6] ?? 'global';
            $resellerId = $scope === 'global' ? CommandCatalog::GLOBAL_PRICE_UUID : $uuid($scope, 'RESELLER_UUID');
            [$tld, $period] = $priceScope($argv[7] ?? '-', $argv[8] ?? '0');
            $stmt = $pdo->prepare(
                'INSERT INTO registry_prices (registry_id, reseller_id, command, amount, currency, tld, period) VALUES (?, ?, ?, ?, ?, ?, ?)
                 ON DUPLICATE KEY UPDATE amount = VALUES(amount), currency = VALUES(currency)'
            );
            $stmt->execute([$registryId, $resellerId, $eppCommand, $amount, $currency, $tld, $period]);
            Audit::record($pdo, $scope === 'global' ? null : $resellerId, 'admin.price_set', 'registry', $registryId, null, [
                'command' => $eppCommand, 'tld' => $tld, 'period' => $period, 'amount' => $amount, 'currency' => $currency, 'scope' => $scope,
            ]);
            echo "Price saved.\n";
            break;

        case 'price:delete':
            $registryId = $uuid($arg(2, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $eppCommand = $arg(3, 'COMMAND');
            CommandCatalog::method($eppCommand);
            $scope = $argv[4] ?? 'global';
            $resellerId = $scope === 'global' ? CommandCatalog::GLOBAL_PRICE_UUID : $uuid($scope, 'RESELLER_UUID');
            [$tld, $period] = $priceScope($argv[5] ?? '-', $argv[6] ?? '0');
            $stmt = $pdo->prepare('DELETE FROM registry_prices WHERE registry_id = ? AND reseller_id = ? AND command = ? AND tld = ? AND period = ?');
            $stmt->execute([$registryId, $resellerId, $eppCommand, $tld, $period]);
            Audit::record($pdo, $scope === 'global' ? null : $resellerId, 'admin.price_deleted', 'registry', $registryId, null, [
                'command' => $eppCommand, 'tld' => $tld, 'period' => $period, 'scope' => $scope, 'count' => $stmt->rowCount(),
            ]);
            echo $stmt->rowCount() . " price(s) deleted.\n";
            break;

        case 'object:assign':
            $registryId = $uuid($arg(2, 'REGISTRY_UUID'), 'REGISTRY_UUID');
            $type = $arg(3, 'domain|contact|host');
            if (!in_array($type, ['domain', 'contact', 'host'], true)) {
                throw new RuntimeException('Invalid object type.');
            }
            $name = Ownership::name($arg(4, 'NAME'), $type);
            $resellerId = $uuid($arg(5, 'RESELLER_UUID'), 'RESELLER_UUID');
            // Import only verified existing objects; never overwrite another owner's mapping or reservation.
            $state = $argv[6] ?? 'active';
            if (!in_array($state, ['active', 'deleted'], true) || $type !== 'domain' && $state !== 'active') {
                throw new RuntimeException('Only domains may be imported as deleted.');
            }
            $stmt = $pdo->prepare('INSERT INTO object_ownership (registry_id, object_type, object_name, reseller_id, active, domain_state, next_check_at) VALUES (?, ?, ?, ?, 1, ?, IF(? = 1, UTC_TIMESTAMP(6), NULL))');
            $stmt->execute([$registryId, $type, $name, $resellerId, $state, (int) ($state === 'deleted')]);
            Audit::record($pdo, $resellerId, 'admin.object_assigned', 'registry', $registryId, null, ['type' => $type, 'name' => $name]);
            echo "Ownership imported.\n";
            break;

        case 'deposit:approve':
            $depositId = $uuid($arg(2, 'DEPOSIT_UUID'), 'DEPOSIT_UUID');
            $deposit = Ledger::approveDeposit($pdo, $depositId);
            Audit::record($pdo, $deposit['reseller_id'], 'admin.deposit_approved', 'deposit', $depositId, null, [
                'amount' => $deposit['amount'], 'currency' => $deposit['currency'],
            ]);
            echo "Deposit approved.\n";
            break;

        case 'deposit:reject':
            $depositId = $uuid($arg(2, 'DEPOSIT_UUID'), 'DEPOSIT_UUID');
            $find = $pdo->prepare('SELECT reseller_id FROM deposit_requests WHERE id = ?');
            $find->execute([$depositId]);
            $resellerId = $find->fetchColumn();
            Ledger::rejectDeposit($pdo, $depositId);
            Audit::record($pdo, $resellerId === false ? null : $resellerId, 'admin.deposit_rejected', 'deposit', $depositId);
            echo "Deposit rejected.\n";
            break;

        case 'job:resolve':
            $jobId = $uuid($arg(2, 'JOB_UUID'), 'JOB_UUID');
            $resolution = $arg(3, 'charge|release');
            $job = Ledger::fetchJob($pdo, $jobId);
            Ledger::resolveUnknown($pdo, $jobId, $resolution);
            Audit::record($pdo, null, 'admin.job_resolved_' . $resolution, 'job', $jobId);
            echo "Unknown job resolved as {$resolution}.\n";
            break;

        case 'job:mark-unknown':
            $jobId = $uuid($arg(2, 'JOB_UUID'), 'JOB_UUID');
            $job = Ledger::fetchJob($pdo, $jobId);
            if ($job['status'] !== 'processing') {
                throw new RuntimeException('Only a processing job can be marked unknown.');
            }
            Ledger::completeJob($pdo, $jobId, 'unknown', [
                'error' => 'operator_marked_unknown',
                'message' => 'The worker outcome requires registry-side reconciliation.',
            ], null);
            Audit::record($pdo, null, 'admin.job_marked_unknown', 'job', $jobId);
            echo "Job marked unknown; its hold remains reserved.\n";
            break;

        default:
            $help();
            exit(1);
    }
} catch (Throwable $e) {
    fwrite(STDERR, 'ERROR: ' . $e->getMessage() . PHP_EOL);
    exit(1);
}
