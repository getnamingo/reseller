const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const inputs = {action: {value: ''}, id: {value: ''}, resolution: {value: ''}, confirmed: {checked: true}};
const text = Object.fromEntries(['#admin-confirmation-title', '[data-action-summary]', '[data-action-confirmation]', '[data-action-submit]'].map(key => [key, {textContent: ''}]));
const form = {reset() { inputs.confirmed.checked = false; }, querySelector(selector) { return inputs[selector.match(/name="([^"]+)"/)[1]]; }};
let onShow;
const modal = {querySelector(selector) { return selector === 'form' ? form : text[selector]; }, addEventListener(name, fn) { assert.equal(name, 'show.bs.modal'); onShow = fn; }};
vm.runInNewContext(fs.readFileSync(`${__dirname}/../panel/public/admin-actions.js`, 'utf8'), {document: {getElementById: () => modal}});
const config = {title: 'Approve', action: 'job.resolve', id: 'first-job', resolution: 'charge', summary: '<script>untrusted</script>', confirmation: 'Verified completed operation'};
let prevented = false;
const show = raw => onShow({relatedTarget: {dataset: {adminAction: raw}}, preventDefault() { prevented = true; }});
show(JSON.stringify(config));
assert.equal(inputs.action.value, 'job.resolve');
assert.equal(inputs.id.value, 'first-job');
assert.equal(inputs.resolution.value, 'charge');
assert.equal(inputs.confirmed.checked, false);
assert.equal(text['[data-action-summary]'].textContent, '<script>untrusted</script>');
assert.equal(text['[data-action-submit]'].textContent, 'Approve');
inputs.confirmed.checked = true;
show(JSON.stringify({...config, action: 'deposit.reject', id: 'second-deposit', resolution: '', title: 'Reject'}));
assert.equal(inputs.id.value, 'second-deposit');
assert.equal(inputs.resolution.value, '');
assert.equal(inputs.confirmed.checked, false);
show('invalid json');
assert.equal(prevented, true);
assert.equal(inputs.id.value, '');
assert.equal(inputs.action.value, '');
console.log('PASS: 13 admin action modal assertions');
